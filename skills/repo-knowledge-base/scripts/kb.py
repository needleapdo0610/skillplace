#!/usr/bin/env python3
"""In-repo knowledge base tool: map source files to the CONTEXT.md that owns them.

Usage (run from the repository root):
  kb.py which FILE...      print the CONTEXT doc that governs each file
  kb.py map                regenerate CONTEXT-MAP.md from every doc's frontmatter
  kb.py check              fail on dead covers patterns, dead path references, stale map
  kb.py changed [BASE]     list docs governing files changed since BASE (default origin/HEAD)
                           and flag docs the diff did not touch; exit 1 if any
  kb.py stale              list docs whose covered files have commits after the doc's
                           `last_verified: <date> @ <sha>`; exit 1 if any
"""
import re
import subprocess
import sys
from fnmatch import fnmatch
from pathlib import Path

MAP_FILE = "CONTEXT-MAP.md"
DOC_RE = re.compile(r"(^|/)CONTEXT(\.[\w-]+)?\.md$")
PATH_REF_RE = re.compile(r"`([A-Za-z0-9_.\-/]+/[A-Za-z0-9_.\-]+)(?::[^`]*)?`")
SKIP_CHANGED = re.compile(r"(^|/)(tests?|e2e|__tests__)/|\.spec\.|(^|/)test_[^/]+$|\.md$|\.lock$|-lock\.json$")


def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True, text=True).stdout


def tracked_files():
    return [f for f in git("ls-files").splitlines() if f]


def parse_frontmatter(text):
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 4)
    if end == -1:
        return {}
    meta, key = {}, None
    for line in text[4:end].splitlines():
        item = re.match(r"\s+-\s+(.+)$", line)
        if item and key:
            meta.setdefault(key, []).append(item.group(1).strip().strip("'\""))
            continue
        pair = re.match(r"([\w-]+):\s*(.*)$", line)
        if pair:
            key, value = pair.group(1), pair.group(2).strip().strip("'\"")
            if value:
                meta[key] = value
    return meta


def load_docs(files):
    docs = {}
    for f in files:
        if DOC_RE.search(f) and Path(f).is_file():
            meta = parse_frontmatter(Path(f).read_text(encoding="utf-8"))
            if isinstance(meta.get("covers"), list):
                docs[f] = meta
    return docs


def owner(path, docs):
    # ponytail: specificity = longest matching pattern; switch to segment-aware scoring if it misroutes
    best, best_len = None, -1
    for doc, meta in docs.items():
        for pattern in meta["covers"]:
            if fnmatch(path, pattern) and len(pattern) > best_len:
                best, best_len = doc, len(pattern)
    return best


def render_map(docs):
    rows = [
        "# Context Map",
        "",
        "Generated by `kb.py map` from each doc's frontmatter. Do not edit by hand.",
        "Before changing a file, open the doc that governs it (`kb.py which <file>`, or the most",
        "specific `covers` match below). After a business change, update that doc in the same PR.",
        "",
        "| Doc | Summary | Covers |",
        "|---|---|---|",
    ]
    for doc in sorted(docs):
        meta = docs[doc]
        covers = "<br>".join(f"`{p}`" for p in meta["covers"])
        rows.append(f"| [{doc}]({doc}) | {meta.get('summary', '')} | {covers} |")
    return "\n".join(rows) + "\n"


def cmd_which(paths, docs):
    for p in paths:
        print(f"{p}\t{owner(p, docs) or '-'}")
    return 0


def cmd_map(docs):
    Path(MAP_FILE).write_text(render_map(docs), encoding="utf-8")
    print(f"wrote {MAP_FILE} ({len(docs)} docs)")
    return 0


def cmd_check(files, docs):
    errors = []
    file_set = set(files)
    dirs = {str(parent) for f in files for parent in Path(f).parents}
    for doc, meta in sorted(docs.items()):
        for pattern in meta["covers"]:
            if not any(fnmatch(f, pattern) for f in files):
                errors.append(f"{doc}: covers pattern matches no tracked file: {pattern}")
        for ref in PATH_REF_RE.findall(Path(doc).read_text(encoding="utf-8")):
            if any(ch in ref for ch in "*<{") or ref.startswith(("http", "~")):
                continue
            ref = ref.rstrip("/")
            if ref not in file_set and ref not in dirs:
                errors.append(f"{doc}: referenced path does not exist: {ref}")
    if not Path(MAP_FILE).is_file() or Path(MAP_FILE).read_text(encoding="utf-8") != render_map(docs):
        errors.append(f"{MAP_FILE} is stale: run `kb.py map`")
    unowned = [f for f in files if not owner(f, docs)]
    for e in errors:
        print(f"ERROR {e}")
    print(f"{len(docs)} docs, {len(files)} tracked files, {len(unowned)} without an owning doc")
    return 1 if errors else 0


def cmd_changed(base, docs):
    merge_base = git("merge-base", base, "HEAD").strip()
    changed = [f for f in git("diff", "--name-only", f"{merge_base}...HEAD").splitlines() if f]
    changed += [f for f in git("diff", "--name-only", "HEAD").splitlines() if f and f not in changed]
    touched = set(changed)
    stale = {}
    for f in changed:
        if SKIP_CHANGED.search(f):
            continue
        doc = owner(f, docs)
        if doc and doc not in touched:
            stale.setdefault(doc, []).append(f)
    for doc, srcs in sorted(stale.items()):
        print(f"{doc} not updated; governs changed: {', '.join(srcs)}")
    if not stale:
        print("every governing doc was touched (or only tests/docs changed)")
    return 1 if stale else 0


VERIFIED_RE = re.compile(r"@\s*([0-9a-f]{7,40})\b")


def cmd_stale(docs):
    stale, problems = {}, []
    for doc, meta in sorted(docs.items()):
        match = VERIFIED_RE.search(str(meta.get("last_verified", "")))
        if not match:
            problems.append(f"{doc}: last_verified has no '@ <sha>'")
            continue
        try:
            names = git("log", f"{match.group(1)}..HEAD", "--name-only", "--format=").splitlines()
        except subprocess.CalledProcessError:
            problems.append(f"{doc}: last_verified sha not found: {match.group(1)}")
            continue
        newer = sorted({f for f in names if f and owner(f, docs) == doc and not SKIP_CHANGED.search(f)})
        if newer:
            stale[doc] = newer
    for doc, srcs in stale.items():
        print(f"{doc} stale: {len(srcs)} governed files changed since last_verified, e.g. {', '.join(srcs[:3])}")
    for p in problems:
        print(f"ERROR {p}")
    if not stale and not problems:
        print("no stale docs")
    return 1 if stale or problems else 0


def main(argv):
    if len(argv) < 2 or argv[1] not in {"which", "map", "check", "changed", "stale"}:
        print(__doc__)
        return 2
    files = tracked_files()
    docs = load_docs(files)
    cmd = argv[1]
    if cmd == "which":
        return cmd_which(argv[2:], docs)
    if cmd == "map":
        return cmd_map(docs)
    if cmd == "check":
        return cmd_check(files, docs)
    if cmd == "stale":
        return cmd_stale(docs)
    return cmd_changed(argv[2] if len(argv) > 2 else "origin/HEAD", docs)


if __name__ == "__main__":
    sys.exit(main(sys.argv))
